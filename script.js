let currentLang = localStorage.getItem("siteLang") || "en";

function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  localStorage.setItem("siteLang", lang);
  langSwitch.textContent = lang === "en" ? "BG" : "EN";

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = translations[lang][node.dataset.i18n];
    if (value) node.textContent = value;
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    const value = translations[lang][node.dataset.i18nAriaLabel];
    if (value) node.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((node) => {
    const value = translations[lang][node.dataset.i18nAlt];
    if (value) node.setAttribute("alt", value);
  });

  document.querySelectorAll("[data-i18n-modal-title]").forEach((node) => {
    const value = translations[lang][node.dataset.i18nModalTitle];
    if (value) node.dataset.modalTitle = value;
  });

  if (translations[lang]["page.title"]) {
    document.title = translations[lang]["page.title"];
  }
}

